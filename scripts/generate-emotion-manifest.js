#!/usr/bin/env node
/**
 * Scans assets/emotions/<emotion>/ for images and writes
 * src/data/emotionImageManifest.ts with static require() calls
 * (Metro cannot bundle dynamic requires).
 *
 * Usage:  npm run emotions:manifest            (max 12 images per emotion)
 *         npm run emotions:manifest -- --max 30
 *
 * Optional difficulty: prefix a file with d1_, d2_ or d3_ (e.g. d2_Training_123.jpg).
 * Files without a prefix default to difficulty 1.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ASSET_DIR = path.join(ROOT, 'assets', 'emotions');
const OUTPUT = path.join(ROOT, 'src', 'data', 'emotionImageManifest.ts');
const EMOTIONS = ['happy', 'sad', 'angry', 'fear', 'surprise', 'disgust', 'neutral'];
const EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);

const maxArgIndex = process.argv.indexOf('--max');
const MAX_PER_EMOTION = maxArgIndex > -1 ? Number(process.argv[maxArgIndex + 1]) || 12 : 12;

function toId(emotion, file) {
  return `${emotion}_${path.parse(file).name.replace(/[^a-zA-Z0-9]+/g, '_').toLowerCase()}`;
}

function difficultyOf(file) {
  const match = /^d([123])_/i.exec(file);
  return match ? Number(match[1]) : 1;
}

const entries = [];
for (const emotion of EMOTIONS) {
  const dir = path.join(ASSET_DIR, emotion);
  if (!fs.existsSync(dir)) continue;
  const files = fs
    .readdirSync(dir)
    .filter((file) => EXTENSIONS.has(path.extname(file).toLowerCase()))
    .sort()
    .slice(0, MAX_PER_EMOTION);
  for (const file of files) {
    entries.push(
      `  { id: '${toId(emotion, file)}', emotion: '${emotion}', difficulty: ${difficultyOf(file)}, source: require('../../assets/emotions/${emotion}/${file}') },`,
    );
  }
  console.log(`${emotion.padEnd(9)} ${files.length} image(s)`);
}

const output = `// AUTO-GENERATED by scripts/generate-emotion-manifest.js — do not edit by hand.
// Add FER2013 images to assets/emotions/<emotion>/ and run: npm run emotions:manifest
import type { ImageSourcePropType } from 'react-native';

import type { Emotion } from '@/types/emotion';

export type EmotionPhotoEntry = {
  id: string;
  emotion: Emotion;
  difficulty: 1 | 2 | 3;
  source: ImageSourcePropType;
};

export const emotionPhotoManifest: EmotionPhotoEntry[] = [${entries.length ? `\n${entries.join('\n')}\n` : ''}];
`;

fs.writeFileSync(OUTPUT, output);
console.log(`\nWrote ${entries.length} image(s) to ${path.relative(ROOT, OUTPUT)}`);
